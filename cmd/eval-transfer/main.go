// eval-transfer tests whether eps chosen on one dataset keeps the survival
// target on another. Input: output/eval/calibrate.json (from cmd/eval-calibrate).
// For every model x G x alpha: pick + certify eps on the source dataset
// (calibration split), then read test survival at that eps on the target.
// Output: output/eval/transfer.json, paper/transfer.gen.tex
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/mikolajsemeniuk/systemonebench/pkg/conformal"
)

type point struct {
	Eps      float64 `json:"eps"`
	NA       int     `json:"n_a"`
	MissesA  int     `json:"misses_a"`
	NB       int     `json:"n_b"`
	MissesB  int     `json:"misses_b"`
	Survival float64 `json:"survival"`
	Calls    float64 `json:"calls_per_decision"`
}

type group struct {
	Model       string  `json:"model"`
	Dataset     string  `json:"dataset"`
	Method      string  `json:"method"`
	Calibration []point `json:"calibration"`
	Test        []point `json:"test"`
}

// Row is one model x G x alpha x (source -> target).
type Row struct {
	Model          string  `json:"model"`
	Method         string  `json:"method"`
	Alpha          float64 `json:"alpha"`
	Source         string  `json:"source"`
	Target         string  `json:"target"`
	Eps            float64 `json:"eps"`
	Certified      bool    `json:"certified"`       // on source
	SourceSurvival float64 `json:"source_survival"` // source test split at eps
	TargetSurvival float64 `json:"target_survival"` // target test split at eps
	TargetHolds    bool    `json:"target_holds"`    // target survival >= 1 - alpha
}

func main() {
	in := flag.String("in", "output/eval/calibrate.json", "input")
	alphas := flag.String("alpha", "0.05,0.1,0.2", "alpha grid")
	outJSON := flag.String("json", "output/eval/transfer.json", "summary json")
	outTex := flag.String("tex", "paper/transfer.gen.tex", "LaTeX table")
	flag.Parse()

	b, err := os.ReadFile(*in)
	if err != nil {
		log.Fatal(err)
	}
	var groups []group
	if err := json.Unmarshal(b, &groups); err != nil {
		log.Fatal(err)
	}
	var rows []Row
	for _, src := range groups {
		for _, dst := range groups {
			if src.Model != dst.Model || src.Method != dst.Method || src.Dataset == dst.Dataset {
				continue
			}
			for _, a := range strings.Split(*alphas, ",") {
				alpha, _ := strconv.ParseFloat(a, 64)
				eps, found := pick(src, alpha)
				if !found {
					continue
				}
				row := Row{Model: src.Model, Method: src.Method, Alpha: alpha, Source: src.Dataset, Target: dst.Dataset,
					Eps: eps, Certified: certify(src, eps, alpha), SourceSurvival: survival(src.Test, eps)}
				row.TargetSurvival = survival(dst.Test, eps)
				row.TargetHolds = row.TargetSurvival >= 1-alpha
				rows = append(rows, row)
			}
		}
	}
	sort.Slice(rows, func(i, j int) bool {
		a, b := rows[i], rows[j]
		if a.Source != b.Source {
			return a.Source < b.Source
		}
		if a.Model != b.Model {
			return a.Model < b.Model
		}
		if a.Method != b.Method {
			return a.Method < b.Method
		}
		return a.Alpha < b.Alpha
	})
	if err := os.MkdirAll(filepath.Dir(*outJSON), 0o755); err != nil {
		log.Fatal(err)
	}
	js, _ := json.MarshalIndent(rows, "", " ")
	if err := os.WriteFile(*outJSON, js, 0o644); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*outTex, []byte(tex(rows)), 0o644); err != nil {
		log.Fatal(err)
	}
	holds, cert := 0, 0
	for _, r := range rows {
		fmt.Printf("%-9s %-12s alpha=%.2f %s->%s eps=%.3f certified=%v source=%.3f target=%.3f holds=%v\n",
			r.Model, r.Method, r.Alpha, r.Source, r.Target, r.Eps, r.Certified, r.SourceSurvival, r.TargetSurvival, r.TargetHolds)
		if r.Certified {
			cert++
			if r.TargetHolds {
				holds++
			}
		}
	}
	fmt.Printf("certified on source: %d, target holds: %d\n", cert, holds)
}

func pick(g group, alpha float64) (float64, bool) {
	var a []conformal.Candidate
	for _, p := range g.Calibration {
		a = append(a, conformal.Candidate{Eps: p.Eps, N: p.NA, Misses: p.MissesA})
	}
	return conformal.Pick(a, alpha)
}

func certify(g group, eps, alpha float64) bool {
	var b []conformal.Candidate
	for _, p := range g.Calibration {
		b = append(b, conformal.Candidate{Eps: p.Eps, N: p.NB, Misses: p.MissesB})
	}
	return conformal.Certify(b, eps, alpha)
}

func survival(pts []point, eps float64) float64 {
	for _, p := range pts {
		if p.Eps == eps {
			return p.Survival
		}
	}
	return 0
}

func tex(rows []Row) string {
	models := []string{"laya", "kev-0.8b", "kev-4b", "kev-9b"}
	datasets := []string{"clinc150", "bfcl", "massive", "banking77"}
	var b strings.Builder
	b.WriteString("% generated by cmd/eval-transfer, do not edit\n")
	b.WriteString("\\begin{tabular}{ll")
	for range datasets {
		b.WriteString("r")
	}
	b.WriteString("r}\n\\toprule\n & & \\multicolumn{4}{c}{Target} & \\\\\n\\cmidrule(lr){3-6}\nModel & Source")
	for _, t := range datasets {
		fmt.Fprintf(&b, " & %s", esc(t))
	}
	b.WriteString(" & Total \\\\\n\\midrule\n")
	for mi, m := range models {
		if mi > 0 {
			b.WriteString("\\midrule\n")
		}
		for _, src := range datasets {
			cells, tn, th, any := "", 0, 0, false
			for _, t := range datasets {
				if t == src {
					cells += " & --"
					continue
				}
				n, h := 0, 0
				for _, r := range rows {
					if r.Model == m && r.Source == src && r.Target == t && r.Certified {
						n++
						if r.TargetHolds {
							h++
						}
					}
				}
				tn += n
				th += h
				if n == 0 {
					cells += " & 0/0"
				} else {
					any = true
					cells += fmt.Sprintf(" & %d/%d", h, n)
				}
			}
			if any {
				fmt.Fprintf(&b, "%s & %s%s & %d/%d \\\\\n", esc(m), esc(src), cells, th, tn)
			}
		}
	}
	b.WriteString("\\bottomrule\n\\end{tabular}\n")
	return b.String()
}

func esc(s string) string { return strings.ReplaceAll(s, "_", "\\_") }
