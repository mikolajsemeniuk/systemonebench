// eval-llm aggregates output/llm/*.jsonl into output/eval/llm.json and
// paper/llm.gen.tex (accuracy, unparsed answers, latency).
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"time"

	"github.com/mikolajsemeniuk/systemonebench/pkg/metrics"
	"github.com/mikolajsemeniuk/systemonebench/pkg/records"
)

// Row is one model × dataset × k.
type Row struct {
	Model    string  `json:"model"`
	Dataset  string  `json:"dataset"`
	K        int     `json:"k"`
	Split    string  `json:"split"`
	N        int     `json:"n"`
	Errors   int     `json:"errors"`
	Unparsed int     `json:"unparsed"` // answer matched no option
	Accuracy float64 `json:"accuracy"`
	P50MS    float64 `json:"p50_ms"`
	P95MS    float64 `json:"p95_ms"`
}

func main() {
	in := flag.String("in", "output/llm", "input directory")
	outJSON := flag.String("json", "output/eval/llm.json", "summary json")
	outTex := flag.String("tex", "paper/llm.gen.tex", "LaTeX table")
	flag.Parse()

	files, _ := filepath.Glob(filepath.Join(*in, "*.jsonl"))
	var rows []Row
	for _, f := range files {
		recs, err := records.Read(f)
		if err != nil {
			log.Fatal(err)
		}
		// <model>.<dataset>.k<k>.<split>.jsonl; model may contain dots
		parts := strings.Split(strings.TrimSuffix(filepath.Base(f), ".jsonl"), ".")
		n := len(parts)
		k, _ := strconv.Atoi(strings.TrimPrefix(parts[n-2], "k"))
		row := Row{Model: strings.Join(parts[:n-3], "."), Dataset: parts[n-3], K: k, Split: parts[n-1], N: len(recs)}
		probs, labels := records.Split(recs)
		var lat []time.Duration
		for _, r := range recs {
			if r.Error != "" {
				row.Errors++
				continue
			}
			lat = append(lat, time.Duration(r.LatencyMS*float64(time.Millisecond)))
			if r.Choice == "" {
				row.Unparsed++
			}
		}
		row.Accuracy = metrics.Accuracy(probs, labels)
		row.P50MS = ms(metrics.Percentile(lat, 50))
		row.P95MS = ms(metrics.Percentile(lat, 95))
		rows = append(rows, row)
	}
	sort.Slice(rows, func(i, j int) bool {
		return rows[i].Dataset+rows[i].Model < rows[j].Dataset+rows[j].Model || (rows[i].Dataset+rows[i].Model == rows[j].Dataset+rows[j].Model && rows[i].K < rows[j].K)
	})
	if err := os.MkdirAll(filepath.Dir(*outJSON), 0o755); err != nil {
		log.Fatal(err)
	}
	b, _ := json.MarshalIndent(rows, "", " ")
	if err := os.WriteFile(*outJSON, b, 0o644); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*outTex, []byte(tex(rows)), 0o644); err != nil {
		log.Fatal(err)
	}
	for _, r := range rows {
		fmt.Printf("%-10s %-9s k=%3d n=%4d acc=%.3f unparsed=%d p50=%.0fms p95=%.0fms\n",
			r.Model, r.Dataset, r.K, r.N, r.Accuracy, r.Unparsed, r.P50MS, r.P95MS)
	}
}

func ms(d time.Duration) float64 { return float64(d.Microseconds()) / 1000 }

func tex(rows []Row) string {
	var b strings.Builder
	b.WriteString("% generated by cmd/eval-llm, do not edit\n")
	b.WriteString("\\begin{tabular}{llrrrr}\n\\toprule\n")
	b.WriteString("Dataset & Model & $k$ & Acc & Unparsed & p50 (ms) \\\\\n\\midrule\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "%s & %s & %d & %.3f & %d & %.0f \\\\\n", esc(r.Dataset), esc(r.Model), r.K, r.Accuracy, r.Unparsed, r.P50MS)
	}
	b.WriteString("\\bottomrule\n\\end{tabular}\n")
	return b.String()
}

func esc(s string) string { return strings.ReplaceAll(s, "_", "\\_") }
