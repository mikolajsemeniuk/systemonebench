// eval-diagnose-k aggregates output/diagnose-k/*.jsonl into
// output/eval/diagnose-k.json and paper/diagnose-k.gen.tex.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"time"

	"github.com/mikolajsemeniuk/systemonebench/pkg/metrics"
	"github.com/mikolajsemeniuk/systemonebench/pkg/records"
)

// Row is one model × dataset × k.
type Row struct {
	Model    string  `json:"model"`
	Dataset  string  `json:"dataset"`
	K        int     `json:"k"`
	N        int     `json:"n"`
	Errors   int     `json:"errors"`
	Accuracy float64 `json:"accuracy"`
	AccRev   float64 `json:"accuracy_reversed"`
	ECE      float64 `json:"ece"`
	Flip     float64 `json:"flip_rate"` // sorted vs reversed order
	P50MS    float64 `json:"p50_ms"`
}

func main() {
	in := flag.String("in", "output/diagnose-k", "input directory")
	outJSON := flag.String("json", "output/eval/diagnose-k.json", "summary json")
	outTex := flag.String("tex", "paper/diagnose-k.gen.tex", "LaTeX table")
	flag.Parse()

	files, _ := filepath.Glob(filepath.Join(*in, "*.sorted.jsonl"))
	var rows []Row
	for _, f := range files {
		sorted, err := records.Read(f)
		if err != nil {
			log.Fatal(err)
		}
		reversed, err := records.Read(strings.Replace(f, ".sorted.jsonl", ".reversed.jsonl", 1))
		if err != nil {
			log.Fatal(err)
		}
		rows = append(rows, summarize(f, sorted, reversed))
	}
	sort.Slice(rows, func(i, j int) bool {
		a, b := rows[i], rows[j]
		if a.Dataset != b.Dataset {
			return a.Dataset < b.Dataset
		}
		if a.Model != b.Model {
			return a.Model < b.Model
		}
		return a.K < b.K
	})
	if err := os.MkdirAll(filepath.Dir(*outJSON), 0o755); err != nil {
		log.Fatal(err)
	}
	b, _ := json.MarshalIndent(rows, "", " ")
	if err := os.WriteFile(*outJSON, b, 0o644); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*outTex, []byte(tex(rows)), 0o644); err != nil {
		log.Fatal(err)
	}
	for _, r := range rows {
		fmt.Printf("%-10s %-10s k=%3d n=%4d acc=%.3f acc_rev=%.3f ece=%.3f flip=%.3f p50=%.1fms\n",
			r.Model, r.Dataset, r.K, r.N, r.Accuracy, r.AccRev, r.ECE, r.Flip, r.P50MS)
	}
}

func summarize(path string, sorted, reversed []records.Record) Row {
	// <model>.<dataset>.k<k>.sorted.jsonl, model may contain dots
	parts := strings.Split(strings.TrimSuffix(filepath.Base(path), ".sorted.jsonl"), ".")
	k, _ := strconv.Atoi(strings.TrimPrefix(parts[len(parts)-1], "k"))
	row := Row{Model: strings.Join(parts[:len(parts)-2], "."), Dataset: parts[len(parts)-2], K: k, N: len(sorted)}
	// keep only examples that succeeded in both orders
	var ps, pr []map[string]float64
	var labels []string
	var lat []time.Duration
	for i := range sorted {
		if sorted[i].Error != "" || reversed[i].Error != "" {
			row.Errors++
			continue
		}
		ps = append(ps, sorted[i].Probabilities)
		pr = append(pr, reversed[i].Probabilities)
		labels = append(labels, sorted[i].Label)
		lat = append(lat, time.Duration(sorted[i].LatencyMS*float64(time.Millisecond)))
	}
	row.Accuracy = metrics.Accuracy(ps, labels)
	row.AccRev = metrics.Accuracy(pr, labels)
	row.ECE = metrics.ECE(ps, labels, 10)
	row.Flip = metrics.FlipRate(ps, pr)
	row.P50MS = float64(metrics.Percentile(lat, 50).Microseconds()) / 1000
	return row
}

func tex(rows []Row) string {
	var b strings.Builder
	b.WriteString("% generated by cmd/eval-diagnose-k, do not edit\n")
	b.WriteString("\\begin{longtable}{llrrrrrr}\n\\toprule\n")
	b.WriteString("Dataset & Model & $k$ & Acc & Acc (rev.) & ECE & Flip & p50 (ms) \\\\\n\\midrule\n\\endfirsthead\n\\toprule\nDataset & Model & $k$ & Acc & Acc (rev.) & ECE & Flip & p50 (ms) \\\\\n\\midrule\n\\endhead\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "%s & %s & %d & %.3f & %.3f & %.3f & %.3f & %.1f \\\\\n",
			strings.ReplaceAll(r.Dataset, "_", "\\_"), strings.ReplaceAll(r.Model, "_", "\\_"), r.K, r.Accuracy, r.AccRev, r.ECE, r.Flip, r.P50MS)
	}
	b.WriteString("\\bottomrule\n\\end{longtable}\n")
	return b.String()
}
