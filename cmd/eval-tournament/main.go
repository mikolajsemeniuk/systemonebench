// eval-tournament aggregates output/tournament/*.jsonl into
// output/eval/tournament.json and paper/tournament.gen.tex.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"time"

	"github.com/mikolajsemeniuk/systemonebench/pkg/metrics"
	"github.com/mikolajsemeniuk/systemonebench/pkg/records"
)

// Row is one model × dataset × k × method.
type Row struct {
	Model    string  `json:"model"`
	Dataset  string  `json:"dataset"`
	K        int     `json:"k"`
	Method   string  `json:"method"`
	Split    string  `json:"split"`
	N        int     `json:"n"`
	Errors   int     `json:"errors"`
	Accuracy float64 `json:"accuracy"`
	MacroF1  float64 `json:"macro_f1"`
	ECE      float64 `json:"ece"`
	Brier    float64 `json:"brier"`
	Calls    float64 `json:"calls_per_decision"`
	P50MS    float64 `json:"p50_ms"`
	P95MS    float64 `json:"p95_ms"`
}

func main() {
	in := flag.String("in", "output/tournament", "input directory")
	outJSON := flag.String("json", "output/eval/tournament.json", "summary json")
	outTex := flag.String("tex", "paper/tournament.gen.tex", "LaTeX table")
	outSummary := flag.String("summary", "paper/tournament-summary.gen.tex", "LaTeX summary table (selected methods)")
	flag.Parse()

	files, _ := filepath.Glob(filepath.Join(*in, "*.jsonl"))
	var rows []Row
	for _, f := range files {
		recs, err := records.Read(f)
		if err != nil {
			log.Fatal(err)
		}
		rows = append(rows, summarize(f, recs))
	}
	sort.Slice(rows, func(i, j int) bool {
		a, b := rows[i], rows[j]
		if a.Dataset != b.Dataset {
			return a.Dataset < b.Dataset
		}
		if a.Model != b.Model {
			return a.Model < b.Model
		}
		if a.K != b.K {
			return a.K < b.K
		}
		return a.Method < b.Method
	})
	if err := os.MkdirAll(filepath.Dir(*outJSON), 0o755); err != nil {
		log.Fatal(err)
	}
	b, _ := json.MarshalIndent(rows, "", " ")
	if err := os.WriteFile(*outJSON, b, 0o644); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*outTex, []byte(tex(rows)), 0o644); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*outSummary, []byte(summary(rows, "clinc150", "CLINC150, $k=150$", "bfcl", "BFCL, $k=255$")), 0o644); err != nil {
		log.Fatal(err)
	}
	more := strings.TrimSuffix(*outSummary, ".gen.tex") + "-more.gen.tex"
	if err := os.WriteFile(more, []byte(summary(rows, "massive", "MASSIVE, $k=59$", "banking77", "Banking77, $k=77$")), 0o644); err != nil {
		log.Fatal(err)
	}
	for _, r := range rows {
		fmt.Printf("%-10s %-9s k=%3d %-22s %-11s n=%4d acc=%.3f ece=%.3f calls=%.1f p50=%.0fms\n",
			r.Model, r.Dataset, r.K, r.Method, r.Split, r.N, r.Accuracy, r.ECE, r.Calls, r.P50MS)
	}
}

func summarize(path string, recs []records.Record) Row {
	// <model>.<dataset>.k<k>.<method>.<split>.jsonl; model may contain dots
	parts := strings.Split(strings.TrimSuffix(filepath.Base(path), ".jsonl"), ".")
	n := len(parts)
	k, _ := strconv.Atoi(strings.TrimPrefix(parts[n-3], "k"))
	row := Row{Model: strings.Join(parts[:n-4], "."), Dataset: parts[n-4], K: k, Method: parts[n-2], Split: parts[n-1], N: len(recs)}
	probs, labels := records.Split(recs)
	var lat []time.Duration
	calls := 0
	for _, r := range recs {
		if r.Error == "" {
			lat = append(lat, time.Duration(r.LatencyMS*float64(time.Millisecond)))
			calls += r.Calls
		}
	}
	row.Errors = len(recs) - len(probs)
	row.Accuracy = metrics.Accuracy(probs, labels)
	row.MacroF1 = metrics.MacroF1(probs, labels)
	row.ECE = metrics.ECE(probs, labels, 10)
	row.Brier = metrics.Brier(probs, labels)
	row.Calls = float64(calls) / float64(max(len(probs), 1))
	row.P50MS = ms(metrics.Percentile(lat, 50))
	row.P95MS = ms(metrics.Percentile(lat, 95))
	return row
}

func ms(d time.Duration) float64 { return float64(d.Microseconds()) / 1000 }

func tex(rows []Row) string {
	models := []string{"laya", "kev-0.8b", "kev-4b", "kev-9b"}
	datasets := []string{"clinc150", "bfcl", "bfcl-nodesc", "massive", "banking77"}
	order := []string{"single", "permute-r4", "permute-r8", "tournament-g8", "tournament-g12", "tournament-g24", "adaptive-g12-eps0p05", "adaptive-g12-eps0p1", "chain-g12-eps0p1", "chain-g24-eps0p1"}
	get := func(ds, m, method string) (Row, bool) {
		for _, r := range rows {
			if r.Dataset == ds && r.Model == m && r.Method == method && r.Split == "test" {
				return r, true
			}
		}
		return Row{}, false
	}
	var b strings.Builder
	b.WriteString("% generated by cmd/eval-tournament, do not edit\n")
	b.WriteString("\\begin{longtable}{ll")
	for range models {
		b.WriteString("rrr")
	}
	b.WriteString("}\n\\toprule\n")
	head := " & "
	for _, m := range models {
		head += fmt.Sprintf(" & \\multicolumn{3}{c}{%s}", esc(m))
	}
	head += " \\\\\n"
	for i := range models {
		head += fmt.Sprintf("\\cmidrule(lr){%d-%d}", 3+3*i, 5+3*i)
	}
	head += "\nDataset & Method"
	for range models {
		head += " & Acc & ECE & Calls"
	}
	head += " \\\\\n\\midrule\n"
	b.WriteString(head + "\\endfirsthead\n\\toprule\n" + head + "\\endhead\n")
	first := true
	for _, ds := range datasets {
		present := false
		for _, r := range rows {
			if r.Dataset == ds {
				present = true
			}
		}
		if !present {
			continue
		}
		if !first {
			b.WriteString("\\midrule\n")
		}
		first = false
		for _, method := range order {
			cells, any := "", false
			for _, m := range models {
				if r, ok := get(ds, m, method); ok {
					any = true
					cells += fmt.Sprintf(" & %.3f & %.2f & %.1f", r.Accuracy, r.ECE, r.Calls)
				} else {
					cells += " & -- & -- & --"
				}
			}
			if any {
				fmt.Fprintf(&b, "%s & %s%s \\\\\n", esc(ds), esc(method), cells)
			}
		}
	}
	b.WriteString("\\bottomrule\n\\end{longtable}\n")
	return b.String()
}

func esc(s string) string { return strings.ReplaceAll(s, "_", "\\_") }

// summary is a compact table: selected methods, CLINC150 and BFCL side by side,
// best accuracy per model and dataset in bold.
func summary(rows []Row, ds1, head1, ds2, head2 string) string {
	methods := []struct{ tag, label string }{
		{"single", "single"},
		{"permute-r8", "permute $R=8$"},
		{"tournament-g24", "tournament $G=24$"},
		{"adaptive-g12-eps0p05", "adaptive $G=12$, $\\varepsilon=0.05$"},
		{"chain-g24-eps0p1", "chain $G=24$, $\\varepsilon=0.1$"},
	}
	models := []string{"laya", "kev-0.8b", "kev-4b", "kev-9b"}
	get := func(model, ds, method string) (Row, bool) {
		for _, r := range rows {
			if r.Model == model && r.Dataset == ds && r.Method == method {
				return r, true
			}
		}
		return Row{}, false
	}
	best := func(model, ds string) float64 {
		b := 0.0
		for _, m := range methods {
			if r, ok := get(model, ds, m.tag); ok && r.Accuracy > b {
				b = r.Accuracy
			}
		}
		return b
	}
	var b strings.Builder
	b.WriteString("% generated by cmd/eval-tournament, do not edit\n")
	b.WriteString("\\begin{tabular}{llrrrrrr}\n\\toprule\n")
	fmt.Fprintf(&b, " & & \\multicolumn{3}{c}{%s} & \\multicolumn{3}{c}{%s} \\\\\n", head1, head2)
	b.WriteString("\\cmidrule(lr){3-5}\\cmidrule(lr){6-8}\nModel & Method & Acc & ECE & p50 (ms) & Acc & ECE & p50 (ms) \\\\\n\\midrule\n")
	for i, model := range models {
		if i > 0 {
			b.WriteString("\\midrule\n")
		}
		for _, m := range methods {
			cells := ""
			any := false
			for _, ds := range []string{ds1, ds2} {
				r, ok := get(model, ds, m.tag)
				if !ok {
					cells += " & -- & -- & --"
					continue
				}
				any = true
				acc := fmt.Sprintf("%.3f", r.Accuracy)
				if r.Accuracy == best(model, ds) {
					acc = "\\textbf{" + acc + "}"
				}
				cells += fmt.Sprintf(" & %s & %.3f & %s", acc, r.ECE, thousands(r.P50MS))
			}
			if any {
				fmt.Fprintf(&b, "%s & %s%s \\\\\n", esc(model), m.label, cells)
			}
		}
	}
	b.WriteString("\\bottomrule\n\\end{tabular}\n")
	return b.String()
}

// thousands formats 12336.5 as 12\,336.
func thousands(ms float64) string {
	n := int(ms + 0.5)
	if n < 1000 {
		return fmt.Sprintf("%d", n)
	}
	return fmt.Sprintf("%d\\,%03d", n/1000, n%1000)
}
