// eval-tournament aggregates output/tournament/*.jsonl into
// output/eval/tournament.json and paper/tournament.gen.tex.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"time"

	"github.com/mikolajsemeniuk/systemonebench/pkg/metrics"
	"github.com/mikolajsemeniuk/systemonebench/pkg/records"
)

// Row is one model × dataset × k × method.
type Row struct {
	Model    string  `json:"model"`
	Dataset  string  `json:"dataset"`
	K        int     `json:"k"`
	Method   string  `json:"method"`
	Split    string  `json:"split"`
	N        int     `json:"n"`
	Errors   int     `json:"errors"`
	Accuracy float64 `json:"accuracy"`
	MacroF1  float64 `json:"macro_f1"`
	ECE      float64 `json:"ece"`
	Brier    float64 `json:"brier"`
	Calls    float64 `json:"calls_per_decision"`
	P50MS    float64 `json:"p50_ms"`
	P95MS    float64 `json:"p95_ms"`
}

func main() {
	in := flag.String("in", "output/tournament", "input directory")
	outJSON := flag.String("json", "output/eval/tournament.json", "summary json")
	outTex := flag.String("tex", "paper/tournament.gen.tex", "LaTeX table")
	flag.Parse()

	files, _ := filepath.Glob(filepath.Join(*in, "*.jsonl"))
	var rows []Row
	for _, f := range files {
		recs, err := records.Read(f)
		if err != nil {
			log.Fatal(err)
		}
		rows = append(rows, summarize(f, recs))
	}
	sort.Slice(rows, func(i, j int) bool {
		a, b := rows[i], rows[j]
		if a.Dataset != b.Dataset {
			return a.Dataset < b.Dataset
		}
		if a.Model != b.Model {
			return a.Model < b.Model
		}
		if a.K != b.K {
			return a.K < b.K
		}
		return a.Method < b.Method
	})
	if err := os.MkdirAll(filepath.Dir(*outJSON), 0o755); err != nil {
		log.Fatal(err)
	}
	b, _ := json.MarshalIndent(rows, "", " ")
	if err := os.WriteFile(*outJSON, b, 0o644); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*outTex, []byte(tex(rows)), 0o644); err != nil {
		log.Fatal(err)
	}
	for _, r := range rows {
		fmt.Printf("%-10s %-9s k=%3d %-22s %-11s n=%4d acc=%.3f ece=%.3f calls=%.1f p50=%.0fms\n",
			r.Model, r.Dataset, r.K, r.Method, r.Split, r.N, r.Accuracy, r.ECE, r.Calls, r.P50MS)
	}
}

func summarize(path string, recs []records.Record) Row {
	// <model>.<dataset>.k<k>.<method>.<split>.jsonl; model may contain dots
	parts := strings.Split(strings.TrimSuffix(filepath.Base(path), ".jsonl"), ".")
	n := len(parts)
	k, _ := strconv.Atoi(strings.TrimPrefix(parts[n-3], "k"))
	row := Row{Model: strings.Join(parts[:n-4], "."), Dataset: parts[n-4], K: k, Method: parts[n-2], Split: parts[n-1], N: len(recs)}
	probs, labels := records.Split(recs)
	var lat []time.Duration
	calls := 0
	for _, r := range recs {
		if r.Error == "" {
			lat = append(lat, time.Duration(r.LatencyMS*float64(time.Millisecond)))
			calls += r.Calls
		}
	}
	row.Errors = len(recs) - len(probs)
	row.Accuracy = metrics.Accuracy(probs, labels)
	row.MacroF1 = metrics.MacroF1(probs, labels)
	row.ECE = metrics.ECE(probs, labels, 10)
	row.Brier = metrics.Brier(probs, labels)
	row.Calls = float64(calls) / float64(max(len(probs), 1))
	row.P50MS = ms(metrics.Percentile(lat, 50))
	row.P95MS = ms(metrics.Percentile(lat, 95))
	return row
}

func ms(d time.Duration) float64 { return float64(d.Microseconds()) / 1000 }

func tex(rows []Row) string {
	var b strings.Builder
	b.WriteString("% generated by cmd/eval-tournament, do not edit\n")
	b.WriteString("\\begin{tabular}{lllrrrrr}\n\\toprule\n")
	b.WriteString("Dataset & Model & Method & $k$ & Acc & ECE & Calls & p50 (ms) \\\\\n\\midrule\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "%s & %s & %s & %d & %.3f & %.3f & %.1f & %.0f \\\\\n",
			esc(r.Dataset), esc(r.Model), esc(r.Method), r.K, r.Accuracy, r.ECE, r.Calls, r.P50MS)
	}
	b.WriteString("\\bottomrule\n\\end{tabular}\n")
	return b.String()
}

func esc(s string) string { return strings.ReplaceAll(s, "_", "\\_") }
