// eval-energy aggregates output/energy/*.json (written by cmd/energy on the
// GPU machine) into paper/energy.gen.tex, adding parameter count and an
// estimated BF16 memory footprint per model (public metadata, not measured).
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// Summary mirrors cmd/energy's output record.
type Summary struct {
	Model         string  `json:"model"`
	Dataset       string  `json:"dataset"`
	Method        string  `json:"method"`
	N             int     `json:"n"`
	Calls         int     `json:"calls"`
	DurationS     float64 `json:"duration_s"`
	IdleWatts     float64 `json:"idle_watts"`
	MeanWatts     float64 `json:"mean_watts"`
	TotalJoules   float64 `json:"total_joules"`
	ActiveJoules  float64 `json:"active_joules"`
	JoulesPerCall float64 `json:"joules_per_call"`
}

// modelInfo is public metadata (model card / file names), not measured here.
type modelInfo struct {
	Params  string // e.g. "421M"
	BF16MiB float64
}

var models = map[string]modelInfo{
	"laya":     {Params: "421M", BF16MiB: 803},
	"kev-0.8b": {Params: "0.8B", BF16MiB: 1600},
	"kev-4b":   {Params: "4B", BF16MiB: 8000},
	"kev-9b":   {Params: "9B", BF16MiB: 18000},
}

func main() {
	in := flag.String("in", "output/energy", "directory with energy json files")
	outTex := flag.String("tex", "paper/energy.gen.tex", "LaTeX table")
	flag.Parse()

	files, _ := filepath.Glob(filepath.Join(*in, "*.json"))
	if len(files) == 0 {
		fmt.Printf("no files in %s; run cmd/energy on the GPU machine first, writing placeholder table\n", *in)
		placeholder := "% placeholder: run `make energy && go run ./cmd/eval-energy` on the GPU machine (GX10) to fill this in\n" +
			"\\begin{tabular}{llrrrrr}\n\\toprule\n" +
			"Model & Params & BF16 (MiB, est.) & Dataset & Idle (W) & Mean (W) & J/decision \\\\\n\\midrule\n" +
			"\\multicolumn{7}{c}{pending measurement on GX10} \\\\\n" +
			"\\bottomrule\n\\end{tabular}\n"
		if err := os.WriteFile(*outTex, []byte(placeholder), 0o644); err != nil {
			log.Fatal(err)
		}
		return
	}
	var rows []Summary
	for _, f := range files {
		b, err := os.ReadFile(f)
		if err != nil {
			log.Fatal(err)
		}
		var s Summary
		if err := json.Unmarshal(b, &s); err != nil {
			log.Fatal(err)
		}
		rows = append(rows, s)
	}
	sort.Slice(rows, func(i, j int) bool {
		if rows[i].Dataset != rows[j].Dataset {
			return rows[i].Dataset < rows[j].Dataset
		}
		if rows[i].Model != rows[j].Model {
			return rows[i].Model < rows[j].Model
		}
		return rows[i].Method < rows[j].Method
	})

	if err := os.WriteFile(*outTex, []byte(tex(rows)), 0o644); err != nil {
		log.Fatal(err)
	}
	for _, r := range rows {
		fmt.Printf("%-10s %-10s %-16s n=%4d calls=%5d idle=%.1fW mean=%.1fW %.3f J/decision\n",
			r.Model, r.Dataset, r.Method, r.N, r.Calls, r.IdleWatts, r.MeanWatts, r.JoulesPerCall)
	}
}

func tex(rows []Summary) string {
	var b strings.Builder
	b.WriteString("% generated by cmd/eval-energy, do not edit\n")
	b.WriteString("\\begin{tabular}{lllrrrrr}\n\\toprule\n")
	b.WriteString("Model & Params & Method & Calls/decision & Idle (W) & Mean (W) & J/decision & J/call \\\\\n\\midrule\n")
	for _, r := range rows {
		info := models[r.Model]
		perCall := 0.0
		if r.Calls > 0 {
			perCall = r.ActiveJoules / float64(r.Calls)
		}
		fmt.Fprintf(&b, "%s & %s & %s & %.1f & %.1f & %.1f & %.2f & %.2f \\\\\n",
			escape(r.Model), info.Params, escape(r.Method), float64(r.Calls)/float64(max(r.N, 1)), r.IdleWatts, r.MeanWatts, r.JoulesPerCall, perCall)
	}
	b.WriteString("\\bottomrule\n\\end{tabular}\n")
	return b.String()
}

func escape(s string) string { return strings.ReplaceAll(s, "_", "\\_") }
