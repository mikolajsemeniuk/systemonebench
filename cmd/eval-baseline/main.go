// eval-baseline aggregates output/baseline/*.jsonl into
// output/eval/baseline.json and paper/baseline.gen.tex.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"

	"github.com/mikolajsemeniuk/systemonebench/pkg/metrics"
	"github.com/mikolajsemeniuk/systemonebench/pkg/records"
)

// Row is the summary of one model × dataset × split file.
type Row struct {
	Model    string  `json:"model"`
	Dataset  string  `json:"dataset"`
	Split    string  `json:"split"`
	N        int     `json:"n"`
	Errors   int     `json:"errors"`
	Options  int     `json:"options"`
	Accuracy float64 `json:"accuracy"`
	MacroF1  float64 `json:"macro_f1"`
	ECE      float64 `json:"ece"`
	Brier    float64 `json:"brier"`
	P50MS    float64 `json:"p50_ms"`
	P95MS    float64 `json:"p95_ms"`
}

func main() {
	in := flag.String("in", "output/baseline", "directory with baseline jsonl files")
	outJSON := flag.String("json", "output/eval/baseline.json", "summary json")
	outTex := flag.String("tex", "paper/baseline.gen.tex", "LaTeX table")
	flag.Parse()

	files, _ := filepath.Glob(filepath.Join(*in, "*.jsonl"))
	var rows []Row
	for _, f := range files {
		recs, err := records.Read(f)
		if err != nil {
			log.Fatal(err)
		}
		rows = append(rows, summarize(f, recs))
	}
	sort.Slice(rows, func(i, j int) bool {
		if rows[i].Dataset != rows[j].Dataset {
			return rows[i].Dataset < rows[j].Dataset
		}
		return rows[i].Model < rows[j].Model
	})
	if err := writeJSON(*outJSON, rows); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*outTex, []byte(tex(rows)), 0o644); err != nil {
		log.Fatal(err)
	}
	for _, r := range rows {
		fmt.Printf("%-10s %-10s %-11s n=%4d acc=%.3f f1=%.3f ece=%.3f brier=%.3f p50=%.1fms\n",
			r.Model, r.Dataset, r.Split, r.N, r.Accuracy, r.MacroF1, r.ECE, r.Brier, r.P50MS)
	}
}

func summarize(path string, recs []records.Record) Row {
	// <model>.<dataset>.<split>.jsonl; model may contain dots (kev-0.8b), so split from the right
	parts := strings.Split(strings.TrimSuffix(filepath.Base(path), ".jsonl"), ".")
	parts = []string{strings.Join(parts[:len(parts)-2], "."), parts[len(parts)-2], parts[len(parts)-1]}
	probs, labels := records.Split(recs)
	var lat []time.Duration
	for _, r := range recs {
		if r.Error == "" {
			lat = append(lat, time.Duration(r.LatencyMS*float64(time.Millisecond)))
		}
	}
	opts := 0
	if len(probs) > 0 {
		opts = len(probs[0])
	}
	return Row{
		Model: parts[0], Dataset: parts[1], Split: parts[2],
		N: len(recs), Errors: len(recs) - len(probs), Options: opts,
		Accuracy: metrics.Accuracy(probs, labels),
		MacroF1:  metrics.MacroF1(probs, labels),
		ECE:      metrics.ECE(probs, labels, 10),
		Brier:    metrics.Brier(probs, labels),
		P50MS:    ms(metrics.Percentile(lat, 50)),
		P95MS:    ms(metrics.Percentile(lat, 95)),
	}
}

func ms(d time.Duration) float64 { return float64(d.Microseconds()) / 1000 }

func writeJSON(path string, v any) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	b, err := json.MarshalIndent(v, "", " ")
	if err != nil {
		return err
	}
	return os.WriteFile(path, b, 0o644)
}

func tex(rows []Row) string {
	var b strings.Builder
	b.WriteString("% generated by cmd/eval-baseline, do not edit\n")
	b.WriteString("\\begin{tabular}{llrrrrrr}\n\\toprule\n")
	b.WriteString("Dataset & Model & $k$ & Acc & F1 & ECE & Brier & p50 (ms) \\\\\n\\midrule\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "%s & %s & %d & %.3f & %.3f & %.3f & %.3f & %.1f \\\\\n",
			escape(r.Dataset), escape(r.Model), r.Options, r.Accuracy, r.MacroF1, r.ECE, r.Brier, r.P50MS)
	}
	b.WriteString("\\bottomrule\n\\end{tabular}\n")
	return b.String()
}

func escape(s string) string { return strings.ReplaceAll(s, "_", "\\_") }
